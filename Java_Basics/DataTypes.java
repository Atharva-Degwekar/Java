public static void main()
{
    // 1 byte = 8 bits

    // simple int size= "1 byte"
    int a = 21;
    System.out.println(a);

    // float with 'f' at the end should be mentioned size= "4 bytes"
    float b = 3.14f;
    System.out.println(b);

    // double size="8 bytes"
    double c = 3.1485E00;
    System.out.println(c);

    // string
    String d = "hello";
    System.out.println(d);

    // Boolean for True/False
    boolean e = true;
    System.out.println(e);

    // char should store in '', size= "1 byte"
    char f = 'h';
    System.out.println(f);

    // byte size= "1 byte"
    byte g = 127;
    System.out.println(g);

    // short size= "2 bytes"
    short h = 32767;
    System.out.println(h);

}