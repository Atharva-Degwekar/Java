public static void main()
{
    //Literals

    // Binary values
    int a = 0b1011;
    int x = 0b1111;
    System.out.println(a);
    System.out.println(x);

    // Hex values
    int b = 0x7E;
    System.out.println(b);

    // Multiple zeros
    int c = 1_00_00_00_000;
    System.out.println(c);

    // double
    double d = 123e21;
    System.out.println(d);

    // long
    long e = 123L;
    System.out.println(e);

    // char
    char f = 'a';
    f++;
    System.out.println(f);
}
